"""Behaviour scoring — how honeypot/sensor-shaped does a host look?

Two phases:

1. **Search phase** (at hunt time, no extra calls). Uses only the banners the
   search returned. Port evidence is *provisional* here because a Shodan
   search returns only banners that matched the query — a query pinned to
   ``port:80`` makes every host look single-port. Provisional signals get
   half weight and are flagged so the analyst knows to inspect.
2. **Inspection phase** (host + history lookup). The candidate is fully
   re-scored from the complete host record: verified port list, SSH,
   40+-port noise gate, first-sighting vs campaign window, banner stability
   (persistent fleets), long churning history (production-like), and the
   multi-honeypot "service zoo" pattern.

A high score is a fingerprint match, not proof.
"""

from __future__ import annotations

import re
import time
from collections import Counter
from datetime import datetime, timezone
from typing import Optional

STRONG = 55
POSSIBLE = 35

CLOUD_HOST_SUFFIXES = [
    "amazonaws.com", "googleusercontent.com", "cloudapp.azure.com", "azurewebsites.net",
    "cloudapp.net", "vultrusercontent.com", "linodeusercontent.com", "linode.com",
    "digitaloceanspaces.com", "digitalocean.com", "oraclecloud.com", "hosting.ovh.net",
    "ip.linodeusercontent.com", "your-server.de", "clients.your-server.de", "contaboserver.net",
]

CLOUD_ORG_HINTS = [
    "amazon", "google", "microsoft", "digitalocean", "hetzner", "oracle", "linode",
    "akamai", "vultr", "choopa", "ovh", "cloudflare", "alibaba", "tencent", "contabo", "scaleway",
]

# RFC 2606 / 6761 special-use TLDs. Providers put these in placeholder rDNS
# (e.g. "…EARLY-REGISTRATION.of.example-nren.invalid"), and Shodan then reports the
# bare TLD as a "domain". Nobody owns them, so they are not a real domain.
PLACEHOLDER_TLDS = {"invalid", "test", "example", "localhost", "local"}
# RFC 2606 also reserves these second-level names for documentation and default configs.
RESERVED_DOMAINS = {"example.com", "example.net", "example.org"}
# Words ISPs and hosters put in generated reverse-DNS names (cpe-1-2-3-4.dyn.isp.net).
PTR_WORDS = re.compile(r"(?:^|[^a-z])(?:ip|dsl|adsl|vdsl|dyn|dynamic|dip|pool|cpe|static|broadband|abo|ppp|pppoe|dhcp|cust|customer|client|host|vps|srv|server|cable|fiber|fibre|ftth|res|user|node)(?:[^a-z]|$)")

GENERIC_TITLE_HINTS = [
    "internal", "portal", "dashboard", "default page",
    "welcome to", "test page", "index of", "apache2", "iis windows", "plesk", "cpanel",
    "webmin", "login", "admin", "home page", "it works", "under construction",
]

PROFILE_KEYS = ["org", "port", "product", "serverVersion", "langBanner", "cms", "country", "city", "vuln", "hostname", "title"]


def clean_profile(raw: Optional[dict]) -> dict:
    raw = raw or {}
    return {k: str(raw.get(k) or "")[:160].strip() for k in PROFILE_KEYS}


def is_web_hunt(profile: dict) -> bool:
    """A hunt profiled on a web stack (the single-port web-persona shape), as opposed to an open-ended hunt."""
    return any((profile or {}).get(k) for k in ("product", "serverVersion", "langBanner", "cms", "port", "title"))


def is_cloud_hostname(hostname: str) -> bool:
    h = hostname.lower().rstrip(".")
    return any(h == s or h.endswith("." + s) for s in CLOUD_HOST_SUFFIXES)


def is_placeholder_domain(name: str) -> bool:
    n = name.lower().strip().rstrip(".")
    if "." not in n:
        return True  # a bare label ("zerofot", "invalid") is not a registrable domain
    return n.rsplit(".", 1)[-1] in PLACEHOLDER_TLDS or any(n == r or n.endswith("." + r) for r in RESERVED_DOMAINS)


def is_provider_ptr(hostname: str, ip: str) -> bool:
    """True if a reverse-DNS name was generated by the network operator from the IP.

    "ip12.ip-198-51-100.hoster.example", "cpe-192-0-2-4.dyn.isp.example" and "pc0000204.dip0.isp.example"
    name the address, not an owner. Such domains belong to the ISP or hoster, so
    they say nothing about who runs the host.
    """
    octets = ip.split(".")
    if len(octets) != 4:
        return False
    h = hostname.lower()
    tokens = set(re.findall(r"\d+", h))
    hits = sum(1 for o in octets if o in tokens or o.zfill(3) in tokens)
    hexed = "".join(f"{int(o):02x}" for o in octets)
    if hexed in h or "".join(o.zfill(3) for o in octets) in h:
        return True
    return hits >= 3 or (hits >= 2 and bool(PTR_WORDS.search(h)))


def owned_domains(data: dict) -> list:
    """Domains that plausibly belong to whoever runs the host.

    Drops cloud, placeholder and reserved names, and domains whose every hostname on
    the record is an operator-generated reverse-DNS name for this IP.
    """
    ip = data.get("ip") or ""
    hostnames = [h.lower().rstrip(".") for h in data.get("hostnames") or []]
    out = []
    for dom in data.get("domains") or []:
        dl = dom.lower().rstrip(".")
        if is_cloud_hostname(dl) or is_placeholder_domain(dl):
            continue
        under = [h for h in hostnames if h == dl or h.endswith("." + dl)]
        if under and all(is_provider_ptr(h, ip) for h in under):
            continue
        out.append(dom)
    return out


def parse_ts(value: Optional[str]) -> Optional[float]:
    """Shodan timestamps are UTC without an offset: 2026-10-23T08:32:44.123456."""
    if not value:
        return None
    v = value.strip().replace("Z", "+00:00")
    try:
        dt = datetime.fromisoformat(v)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.timestamp()


def window_bounds(start: Optional[str], end: Optional[str]) -> "tuple[Optional[float], Optional[float]]":
    """Campaign window dates are interpreted as whole UTC days."""
    s = parse_ts(start + "T00:00:00") if start else None
    e = parse_ts(end + "T23:59:59.999999") if end else None
    return s, e


def band_for(score: int) -> str:
    return "strong" if score >= STRONG else "possible" if score >= POSSIBLE else "weak"


NOISE_CAP = POSSIBLE - 1  # hosts that answer on everything can never rank above "weak"


class _Acc:
    def __init__(self) -> None:
        self.signals: list[dict] = []
        self.cap: "int | None" = None

    def add(self, key: str, label: str, points: int, detail: str = "", phase: str = "search", provisional: bool = False) -> None:
        self.signals.append({"key": key, "label": label, "points": points, "detail": detail, "phase": phase, "provisional": provisional})

    def result(self) -> dict:
        return finalize(self.signals, self.cap is not None)


def finalize(signals: list[dict], capped: bool) -> dict:
    raw = sum(s["points"] for s in signals)
    score = max(0, min(100, raw))
    if capped and score > NOISE_CAP:
        score = NOISE_CAP
    return {"score": score, "raw": raw, "band": band_for(score), "signals": signals, "capped": capped}


def _base_signals(acc: _Acc, d: dict, profile: dict) -> None:
    verified = bool(d.get("ports_verified"))
    hostnames = d.get("hostnames") or []
    domains = d.get("domains") or []
    ports = d.get("ports") or []

    # Identity: bare cloud PTR vs a real domain someone owns.
    if hostnames and all(is_cloud_hostname(h) for h in hostnames):
        acc.add("bare_hostname", "Bare cloud hostname only", 18, hostnames[0])
    real = owned_domains(d)
    if not real:
        if not domains:
            why = "No domains on the record"
        elif any(is_placeholder_domain(x) for x in domains):
            why = "Only cloud-provider, placeholder or reserved domains (" + ", ".join(domains[:3]) + ")"
        elif all(is_cloud_hostname(x) for x in domains):
            why = "Only cloud-provider domains"
        else:
            why = "Only the network operator's reverse-DNS domains (" + ", ".join(domains[:3]) + ")"
        acc.add("no_real_domain", "No real domain attached", 10, why)
    else:
        acc.add("real_domain", "Real domain attached", -15, ", ".join(real[:3]))

    # Port shape. Search results only show matched banners -> provisional.
    if verified:
        if len(ports) >= 40:
            acc.add("answers_everything", "Answers on 40+ ports — noise gate (score capped at weak)", -30, f"{len(ports)} open ports; any banner query matches this host, so fingerprint evidence is meaningless. Likely a tarpit / port-spoofer, not this fleet", "inspection")
            acc.cap = NOISE_CAP
        elif len(ports) == 1:
            acc.add("single_port", "Single open port (verified)", 18, f"Only port {ports[0]} is open", "inspection")
        elif 2 <= len(ports) <= 3:
            acc.add("few_ports", "Very few open ports (verified)", 4, ", ".join(map(str, ports)), "inspection")
        elif len(ports) > 3:
            acc.add("many_ports", "Many open ports", -12, ", ".join(map(str, ports[:10])), "inspection")
    else:
        if len(ports) == 1:
            acc.add("single_port", "Single matched port (unverified — inspect to confirm)", 9, f"Only port {ports[0]} matched the query", provisional=True)
        elif 2 <= len(ports) <= 3:
            acc.add("few_ports", "Few matched ports (unverified)", 2, ", ".join(map(str, ports)), provisional=True)
        elif len(ports) > 3:
            acc.add("many_ports", "Many open ports", -12, ", ".join(map(str, ports[:10])))
    if 22 in ports and is_web_hunt(profile):
        # Web-persona sensors (the single-port web-persona shape) expose no SSH. Multi-honeypot hosts
        # run an SSH honeypot (Cowrie), so outside web hunts SSH is not evidence either way.
        acc.add("ssh_open", "SSH exposed", -10, "Port 22 open; web-persona sensors like the reference fleet expose no SSH", "inspection" if verified else "search")

    # Persona: bland internal page titles.
    title = d.get("title")
    if title:
        low = title.lower()
        if any(h in low for h in GENERIC_TITLE_HINTS) or (profile.get("title") and profile["title"].lower() in low):
            acc.add("generic_title", "Generic / internal page title", 10, f'"{title}"')
    else:
        acc.add("no_title", "No page title", 4, "The HTTP service exposes no title")

    # Vulnerability flags (Shodan's are banner-derived, i.e. version-based).
    vulns = d.get("vulns") or []
    if profile.get("vuln") and profile["vuln"].upper() in (v.upper() for v in vulns):
        acc.add("vuln_match", "Flagged for the profile CVE", 15, profile["vuln"])
    elif len(vulns) >= 5:
        acc.add("vuln_heavy", "Heavily vuln-flagged (banner-derived)", 3, f"{len(vulns)} CVEs on the record")

    # Tenancy and Shodan's own labels.
    org = (d.get("org") or "").lower()
    if any(h in org for h in CLOUD_ORG_HINTS):
        acc.add("cloud_org", "Cloud provider tenancy", 5, d.get("org") or "")
    tags = d.get("tags") or []
    if "cloud" in tags:
        acc.add("cloud_tag", "Shodan 'cloud' tag", 3, "Tagged cloud by Shodan")
    if "honeypot" in tags:
        acc.add("honeypot_tag", "Shodan 'honeypot' tag", 20, "Shodan itself classifies this host as a honeypot")
    hints = d.get("software_hints") or []
    if hints:
        acc.add("honeypot_software", "Known honeypot software fingerprint", 25, ", ".join(hints[:5]))


def _last_seen_timing(acc: _Acc, d: dict, window: "tuple[Optional[float], Optional[float]]", now: float) -> None:
    seen = parse_ts(d.get("last_seen"))
    if seen is None:
        return
    s, e = window
    if s is not None and e is not None and s <= seen <= e:
        acc.add("in_window", "Observed inside the campaign window", 15, f"Last Shodan observation {d.get('last_seen')} UTC")
    elif now - seen < 14 * 86400:
        acc.add("fresh", "Recently observed by Shodan", 6, f"Last observation {d.get('last_seen')} UTC")


def score_search(d: dict, profile: dict, window_start: Optional[str], window_end: Optional[str], now: Optional[float] = None) -> dict:
    acc = _Acc()
    _base_signals(acc, d, profile)
    _last_seen_timing(acc, d, window_bounds(window_start, window_end), now or time.time())
    return acc.result()


def history_signals(detail: dict, profile: dict, window_start: Optional[str], window_end: Optional[str]) -> "tuple[list[dict], bool]":
    """Signals that need the host-history drill-down. Returns (signals, used_first_seen)."""
    acc = _Acc()
    tl = detail.get("timeline") or []
    used_first_seen = False
    if tl:
        firsts = [x for x in (parse_ts(t["first_seen"]) for t in tl) if x is not None]
        lasts = [x for x in (parse_ts(t["last_seen"]) for t in tl) if x is not None]
        total_obs = sum(t.get("observations", 0) for t in tl)
        if firsts and lasts and total_obs:
            first, last = min(firsts), max(lasts)
            span_days = int((last - first) // 86400)
            first_iso = min(t["first_seen"] for t in tl)

            s, e = window_bounds(window_start, window_end)
            if s is not None and e is not None:
                used_first_seen = True
                if s <= first <= e:
                    acc.add("first_seen_in_window", "First sighted inside the campaign window", 15, f"Earliest Shodan observation {first_iso} UTC", "inspection")

            if total_obs == 1:
                acc.add("single_sighting", "Single Shodan sighting", 4, f"Only one observation ever ({first_iso} UTC)", "inspection")

            stable = all(len(t.get("products") or []) <= 1 and len(t.get("titles") or []) <= 1 for t in tl)
            vuln = profile.get("vuln") or ""
            still_vuln = vuln.upper() in (v.upper() for v in detail.get("vulns") or []) if vuln else bool(detail.get("vulns"))
            months = max(1, round(span_days / 30))
            label_v = vuln or "vulnerable-version flags"
            if stable and still_vuln:
                if span_days >= 180 and total_obs >= 3:
                    acc.add("banner_stability", "Frozen banner across many months (persistent-fleet pattern)", 18, f"Same product/version and title on every port across {total_obs} observations spanning ~{months} months, still flagged for {label_v}", "inspection")
                elif span_days >= 90 and total_obs >= 3:
                    acc.add("banner_stability", "Frozen banner across months (persistent-fleet pattern)", 14, f"Same product/version and title on every port across {total_obs} observations spanning ~{months} months, still flagged for {label_v}", "inspection")
                elif span_days >= 30 and total_obs >= 2:
                    acc.add("banner_stability", "Stable banner over time", 7, f"Unchanged product across {total_obs} observations spanning {span_days} days, still flagged for {label_v}", "inspection")
            elif not stable and span_days >= 180:
                changed = [str(t["port"]) for t in tl if len(t.get("products") or []) > 1 or len(t.get("titles") or []) > 1]
                acc.add("long_churn", "Long history with changing services (production-like)", -12, f"~{months} months of history; banner/title changed on port(s) {', '.join(changed[:6])}", "inspection")
    return acc.signals, used_first_seen


SERVICE_FAMILIES = [
    ("web", ("apache", "nginx", "iis", "basehttpserver", "tomcat", "jetty", "lighttpd", "caddy", "werkzeug", "http")),
    ("ssh", ("openssh", "dropbear", "ssh")),
    ("mail", ("exim", "postfix", "sendmail", "dovecot", "smtp", "imap", "pop3")),
    ("sql", ("ms-sql", "mssql", "mysql", "mariadb", "postgresql", "oracle")),
    ("nosql", ("redis", "mongodb", "elastic", "memcache", "couchdb", "cassandra")),
    ("remote", ("vnc", "rdp", "remote desktop", "radmin", "telnet", "teamviewer")),
    ("mq", ("mqtt", "amqp", "rabbitmq", "kafka")),
    ("vpn", ("pptp", "openvpn", "ipsec", "l2tp")),
    ("proxy", ("socks", "squid", "proxy")),
    ("windows", ("microsoft rpc", "msrpc", "smb", "netbios", "microsoft-ds", "samba")),
    ("ics", ("modbus", "s7", "siemens", "bacnet", "dnp3", "iec", "ipmi", "conpot", "gaspot", "ethernet/ip")),
    ("file", ("ftp", "tftp", "nfs", "rsync")),
    ("voip", ("sip", "asterisk")),
    ("dev", ("adb", "docker", "kubernetes", "etcd", "jenkins", "gitlab")),
]
# Products long out of support that honeypots still emulate by default (Dionaea's MS-SQL).
EMULATED_LEGACY = ("ms-sql server 2000", "sql server 2000")
ZOO_MIN_FAMILIES = 6


def service_families(detail: dict) -> "dict[str, list[str]]":
    fams: dict = {}
    for s in (detail or {}).get("services") or []:
        prod = (s.get("product") or "").lower()
        if not prod:
            continue
        for fam, needles in SERVICE_FAMILIES:
            if any(n in prod for n in needles):
                fams.setdefault(fam, [])
                if s["product"] not in fams[fam]:
                    fams[fam].append(s["product"])
                break
    return fams


def _service_signals(acc: _Acc, detail: dict) -> None:
    """Multi-honeypot hosts (T-Pot style) run many unrelated emulated services on one IP.

    A tarpit answers every port with the same thing; a production box runs a few
    related services. Six or more unrelated service families with real banners is
    the honeypot-platform shape, so such a host is not noise and is not capped.
    """
    fams = service_families(detail)
    if len(fams) >= ZOO_MIN_FAMILIES:
        acc.add("service_zoo", "Many unrelated services on one host (multi-honeypot pattern)", 15,
                f"{len(fams)} service families: " + ", ".join(f"{k} ({v[0]})" for k, v in list(fams.items())[:8]), "inspection")
        if acc.cap is not None:
            acc.cap = None
            acc.signals = [{**s, "points": -12, "label": "Answers on 40+ ports, but with distinct real services (not a tarpit)"} if s["key"] == "answers_everything" else s for s in acc.signals]
    legacy = sorted({p for v in fams.values() for p in v if any(x in p.lower() for x in EMULATED_LEGACY)})
    if legacy:
        acc.add("emulated_legacy", "Out-of-support product typical of honeypot emulation", 8, ", ".join(legacy[:3]), "inspection")


def score_inspected(d: dict, detail: dict, profile: dict, window_start: Optional[str], window_end: Optional[str], now: Optional[float] = None) -> dict:
    """Full re-score from a verified host record + history."""
    acc = _Acc()
    _base_signals(acc, d, profile)
    _service_signals(acc, detail)
    hist, used_first_seen = history_signals(detail, profile, window_start, window_end)
    if not used_first_seen or not detail.get("timeline"):
        # No window or no history: fall back to last-seen timing.
        _last_seen_timing(acc, d, window_bounds(window_start, window_end), now or time.time())
    acc.signals.extend(hist)
    return acc.result()


# ---- cluster phase ---------------------------------------------------------
#
# Per-host signals can be dodged one host at a time (add a decoy port, attach a
# throwaway domain, front with a port-spoofer). What a fleet cannot cheaply
# avoid is being a fleet: cloned content, cloned keys, one address block, one
# deployment burst. These signals look across every candidate in the hunt.

CLUSTER_MIN = 3            # hosts that must share a persona before it counts
COMMON_GLOBAL = 1000       # a fingerprint seen on more Shodan hosts than this is not a template
BURST_HOURS = 48
BURST_MAX_OBS = 5          # a fresh deployment has few sightings; long-lived hosts sit at the history horizon
EMPTY_PAGE_HASHES = {"0"}  # Shodan's html_hash for an empty body
DEFAULT_PAGE_TITLES = [
    "welcome to nginx", "apache2 debian default page", "apache2 ubuntu default page", "it works", "test page for",
    "iis windows server", "index of /", "502 bad gateway", "default web site page",
    "site under construction", "coming soon", "domain for sale", "login",
    # Bare HTTP status pages: every redirecting or locked-down server serves these.
    "301 moved permanently", "302 found", "303 see other", "307 temporary redirect", "308 permanent redirect",
    "moved permanently", "object moved", "document moved", "redirect", "400 bad request", "401 unauthorized",
    "403 forbidden", "forbidden", "access denied", "404 not found", "not found", "405 not allowed", "500 internal server error",
    "503 service unavailable", "service unavailable", "504 gateway time-out", "error",
]
_PERSONA_FILTERS = {"html": "http.html_hash", "title": "http.title"}


def is_default_title(title: Optional[str]) -> bool:
    low = (title or "").lower()
    return not low or any(t in low for t in DEFAULT_PAGE_TITLES)


def _looks_unowned(name: str) -> bool:
    n = name.lower().strip().rstrip(".")
    return not n or "." not in n or is_placeholder_domain(n) or is_cloud_hostname(n) or n.replace(".", "").isdigit()


def _real_domains(data: dict) -> set:
    return {x.lower() for x in owned_domains(data)}


def _first_seen(detail: Optional[dict]) -> Optional[float]:
    """First sighting of a recently deployed host, or None.

    Shodan's history only reaches back so far, so a long-lived server looks "first
    seen" at the start of that horizon, together with every other long-lived server.
    Hosts with many sightings are therefore not treated as fresh deployments.
    """
    tl = (detail or {}).get("timeline") or []
    if sum(t.get("observations", 0) for t in tl) > BURST_MAX_OBS:
        return None
    firsts = [x for x in (parse_ts(t.get("first_seen")) for t in tl) if x is not None]
    return min(firsts) if firsts else None


def _persona_values(data: dict, kind: str) -> list[str]:
    if kind == "title":
        titles = list((data.get("fp") or {}).get("title") or []) or ([data["title"]] if data.get("title") else [])
        return [t for t in titles if not is_default_title(t)]
    return [v for v in (data.get("fp") or {}).get(kind) or [] if v not in EMPTY_PAGE_HASHES]


def _sig(key: str, label: str, points: int, detail: str) -> dict:
    return {"key": key, "label": label, "points": points, "detail": detail, "phase": "cluster", "provisional": False}


def cluster_signals(entries: list[dict], profile: dict, query: str = "", prevalence: Optional[dict] = None) -> dict:
    """entries: [{key, data, detail, capped}] -> {key: (signals, lift_noise_cap)}.

    ``prevalence`` maps (kind, value) -> total hosts on all of Shodan (from the
    free ``pivot`` counts). It turns "shared inside this hunt" into "rare
    template" or "globally common", which is what separates a cloned fleet from
    a popular default page.
    """
    prevalence = prevalence or {}
    m = len(entries)
    out: dict = {e["key"]: ([], False) for e in entries}
    if m < 2:
        return out
    q = (query or "").lower()
    skip = {k for k, f in _PERSONA_FILTERS.items() if f in q}  # shared by construction of the query
    if profile.get("title"):
        skip.add("title")

    # 1. Shared persona (cloned page or title), weighted by global rarity.
    members: dict = {}
    for e in entries:
        for kind in ("html", "title"):
            if kind in skip:
                continue
            for v in _persona_values(e["data"], kind):
                members.setdefault((kind, v), []).append(e)
    # An html hash only counts if its hosts don't all serve a default page.
    for (kind, v), es in list(members.items()):
        if kind == "html" and all(is_default_title(x["data"].get("title")) for x in es):
            del members[(kind, v)]
    by_key: dict = {}
    for kv, es in members.items():
        if len(es) >= CLUSTER_MIN:
            for x in es:
                by_key.setdefault(x["key"], []).append(kv)

    def persona_for(e: dict):
        best = None
        for kind, v in by_key.get(e["key"], []):
            n, total = len(members[(kind, v)]), prevalence.get((kind, v))
            if total is not None and total > max(COMMON_GLOBAL, 10 * n):
                pts = 0
            elif total is not None:
                pts = 15
            else:
                pts = 10
            cand = (pts, n, kind, v, total)
            if best is None or cand[:2] > best[:2]:
                best = cand
        return best

    # 2. Cloned keys: one SSH host key, or one unowned TLS cert, on several IPs.
    ssh_hosts: dict = {}
    cert_hosts: dict = {}
    for e in entries:
        fp = e["data"].get("fp") or {}
        for v in fp.get("ssh") or []:
            ssh_hosts.setdefault(v, set()).add(e["data"]["ip"])
        subjects = e["data"].get("cert_subjects") or []
        if e["data"].get("cert_self_signed") or (subjects and all(_looks_unowned(s) for s in subjects)):
            for v in fp.get("cert") or []:
                cert_hosts.setdefault(v, set()).add(e["data"]["ip"])

    # 3. Address density and 4. deployment burst.
    blocks: dict = {}
    for e in entries:
        parts = e["data"]["ip"].split(".")
        if len(parts) == 4:
            blocks.setdefault(".".join(parts[:3]), []).append(e)
    dense_min = max(5, -(-m * 25 // 100))
    firsts = {e["key"]: _first_seen(e.get("detail")) for e in entries}
    known = [t for t in firsts.values() if t is not None]
    burst_min = max(5, -(-len(known) * 25 // 100))

    for e in entries:
        sig: list[dict] = []
        d = e["data"]
        lift = False
        p = persona_for(e)
        if p:
            pts, n, kind, v, total = p
            what = f'title "{v}"' if kind == "title" else f"page hash {v}"
            if pts == 0:
                sig.append(_sig("shared_persona", "Shared persona, but globally common", 0, f"{n} of {m} hunt hosts serve {what}, but Shodan sees it on {total:,} hosts: a common page, not a fleet template"))
            elif total is not None:
                sig.append(_sig("shared_persona", "Rare cloned persona (fleet template)", pts, f"{n} of {m} hunt hosts serve {what}; only {total:,} hosts on all of Shodan"))
            else:
                sig.append(_sig("shared_persona", "Cloned persona across the hunt", pts, f"{n} of {m} hunt hosts serve {what} (run `pivot` to check global rarity)"))
            if e.get("capped") and pts > 0:
                peers_uncapped = sum(1 for x in members[(kind, v)] if not x.get("capped"))
                if peers_uncapped >= 2 or total is not None:
                    lift = True
                    sig.append(_sig("noise_gate_lifted", "Noise gate lifted: persona matches the fleet", 0, f"Answers on many ports, but serves the same rare persona as {peers_uncapped} hunt hosts that don't, so the match is not an accident of answering everything"))
        if p and p[0] > 0 and p[2] == "html":
            # Decoys are one throwaway domain per host. Domains shared between hosts are one
            # owner's multi-domain estate (a CDN or a site family), which is not evidence.
            peers = members[(p[2], p[3])]
            seen = Counter(dom for x in peers for dom in _real_domains(x["data"]))
            own = {dom for dom in _real_domains(d) if seen[dom] == 1}
            if own and not (_real_domains(d) - own):
                doms = {dom for dom, n in seen.items() if n == 1}
                if len(doms) >= CLUSTER_MIN:
                    sig.append(_sig("decoy_domains", "Same page under many domains (decoy domains)", 15, f"Byte-identical page served under {len(doms)} different domains in this hunt, including {', '.join(sorted(own)[:2])}. Real sites embed their own domain, so the real-domain penalty is offset"))
        shared_ssh = max((len(ssh_hosts[v]) for v in (d.get("fp") or {}).get("ssh") or [] if v in ssh_hosts), default=0)
        if shared_ssh >= 2:
            sig.append(_sig("cloned_host_key", "SSH host key cloned across IPs", 12, f"The same SSH host key is on {shared_ssh} hunt hosts: one disk image deployed many times"))
        shared_cert = max((len(cert_hosts[v]) for v in (d.get("fp") or {}).get("cert") or [] if v in cert_hosts), default=0)
        if shared_cert >= 2:
            sig.append(_sig("cloned_cert", "Unowned TLS certificate cloned across IPs", 8, f"The same self-signed or domainless certificate is on {shared_cert} hunt hosts"))
        parts = d["ip"].split(".")
        if len(parts) == 4:
            blk = blocks.get(".".join(parts[:3]), [])
            if len(blk) >= dense_min:
                sig.append(_sig("dense_block", "Dense address block", 5, f"{len(blk)} of {m} hunt hosts sit in {'.'.join(parts[:3])}.0/24"))
        t = firsts[e["key"]]
        if t is not None:
            near = sum(1 for x in known if abs(x - t) <= BURST_HOURS * 3600)
            if near >= burst_min:
                sig.append(_sig("deployment_burst", "Deployed in a burst with its peers", 6, f"{near} of {len(known)} inspected hunt hosts were first seen within {BURST_HOURS} h of this one"))
        out[e["key"]] = (sig, lift)
    return out


def score_hunt(entries: list[dict], profile: dict, window_start: Optional[str], window_end: Optional[str], query: str = "",
               prevalence: Optional[dict] = None, now: Optional[float] = None) -> dict:
    """Score every candidate of a hunt: per-host signals, then cluster signals.

    entries: [{key, data, detail}] (detail None = search phase only). Makes no API calls.
    """
    profile = clean_profile(profile)
    base = {}
    for e in entries:
        if e.get("detail"):
            base[e["key"]] = score_inspected(e["data"], e["detail"], profile, window_start, window_end, now)
        else:
            base[e["key"]] = score_search(e["data"], profile, window_start, window_end, now)
    clustered = cluster_signals([{**e, "capped": base[e["key"]]["capped"]} for e in entries], profile, query, prevalence)
    out = {}
    for e in entries:
        sig, lift = clustered.get(e["key"], ([], False))
        r = base[e["key"]]
        own = r["signals"]
        if lift:
            own = [{**s, "points": -12, "label": "Answers on 40+ ports (noise gate lifted, counted as many ports)"} if s["key"] == "answers_everything" else s for s in own]
        out[e["key"]] = finalize(own + sig, r["capped"] and not lift)
    return out


def evasion_cost(signals: list[dict], capped: bool) -> "tuple[int, list[str]]":
    """Fewest positive signals an adversary must defeat to drop a host to weak (greedy, largest first)."""
    pos = sorted((s for s in signals if s["points"] > 0), key=lambda s: -s["points"])
    rest = list(signals)
    removed: list[str] = []
    while finalize(rest, capped)["band"] != "weak" and pos:
        s = pos.pop(0)
        rest = [x for x in rest if x is not s]
        removed.append(s["key"])
    return len(removed), removed
